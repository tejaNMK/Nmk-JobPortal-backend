"""AI Interview Answer Evaluation schemas.

Evaluated by AWS Bedrock (see `app.service.ai_service.AIService`, the same
Bedrock integration `AIInterviewQuestionService` / `JobMatchService` /
`AICoverLetterService` already use) from one specific job posting, one
interview question, and the logged-in candidate's own answer to it --
grounded in the candidate's existing profile and latest resume so the
evaluation (and the suggested improved answer) never credits the
candidate with experience or qualifications they haven't actually
reported.

Kept as its own module -- mirroring `app/schema/ai_cover_letter.py` and
`app/schema/ai_interview_question.py` -- since this is a distinct AI
feature with its own request/response shape, not a variant of the
Interview Question Generator's schema.
"""

from __future__ import annotations

from pydantic import BaseModel, ConfigDict, Field, field_validator

MIN_QUESTION_LENGTH = 1
MAX_QUESTION_LENGTH = 1000

MIN_ANSWER_LENGTH = 1
MAX_ANSWER_LENGTH = 8000


class AIInterviewAnswerEvaluationRequest(BaseModel):
    """Request body for `POST /candidate/interview-answer/evaluate`.

    `job_id` is required -- the answer is always evaluated against one
    specific job posting (title, company, skills, responsibilities, and
    requirements pulled server side, never trusted from the client).
    `question` is the interview question being answered (typically one
    generated by the existing AI Interview Question Generator, but any
    question text is accepted -- this endpoint does not require the
    question to have been AI-generated). `answer` is the candidate's own
    answer, exactly as they intend to give it.
    """

    job_id: str = Field(
        min_length=1,
        description="The job posting to evaluate this answer against.",
    )
    question: str = Field(
        min_length=MIN_QUESTION_LENGTH,
        max_length=MAX_QUESTION_LENGTH,
        description="The interview question the candidate is answering.",
    )
    answer: str = Field(
        min_length=MIN_ANSWER_LENGTH,
        max_length=MAX_ANSWER_LENGTH,
        description="The candidate's own answer to the question, to be evaluated.",
    )

    @field_validator("job_id", "question", "answer")
    @classmethod
    def _must_have_content(cls, value: str) -> str:
        if not value.strip():
            raise ValueError("must not be blank")
        return value


class AIInterviewAnswerEvaluationResponse(BaseModel):
    """AI Interview Answer Evaluation API response.

    `overall_score` is the AI's holistic 0-100 assessment of the answer;
    `technical_accuracy`, `relevance`, and `clarity` are the three
    sub-scores (also 0-100) it is based on. `suggested_improved_answer`
    is grounded strictly in the candidate's own profile/resume -- like
    `AIInterviewQuestionService`'s sample answers, it never adds an
    employer, project, tool, metric, or skill the candidate hasn't
    actually reported.
    """

    job_id: str = Field(description="The job posting this evaluation was performed against.")
    job_title: str = Field(description="The job's title, echoed from the job posting (not AI-generated).")
    company_name: str = Field(
        default="",
        description="The hiring company's name, echoed from the job posting (not AI-generated).",
    )
    question: str = Field(description="The interview question that was answered, echoed back verbatim.")

    overall_score: float = Field(
        ge=0,
        le=100,
        description="Holistic AI-assessed quality of the answer for this job and question (0-100).",
    )
    technical_accuracy: float = Field(
        ge=0,
        le=100,
        description="How technically correct and sound the answer is (0-100).",
    )
    relevance: float = Field(
        ge=0,
        le=100,
        description="How directly the answer addresses the question and this specific job (0-100).",
    )
    clarity: float = Field(
        ge=0,
        le=100,
        description="How clear, well-structured, and easy to follow the answer is (0-100).",
    )

    strengths: list[str] = Field(
        default_factory=list,
        description="What the answer does well.",
    )
    areas_for_improvement: list[str] = Field(
        default_factory=list,
        description="Specific weaknesses or gaps in the answer.",
    )
    detailed_feedback: str = Field(
        default="",
        description="A concise, human-readable explanation of the evaluation and scores.",
    )
    suggested_improved_answer: str = Field(
        default="",
        description=(
            "A stronger version of the candidate's answer, grounded only "
            "in the candidate's own reported background -- never invents "
            "experience or qualifications the candidate doesn't have."
        ),
    )

    model_config = ConfigDict(from_attributes=True)